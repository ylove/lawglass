// The model picks ids from closed enums (see core/model/picture.ts); this file is the only place
// that turns an id into a drawing. Every glyph is a plain lucide line icon, so panels read as
// clip art, not decoration: no faces, no flags, no party colours, no weapons. Both maps are full
// Records, so adding an id to the contract fails the typecheck until it has an icon here.
//
// Choices that matter for the common cases:
// - bank is Landmark (columns and a pediment); government is University, a different roofline
//   with steps, so "the bank pays the government" does not draw the same building twice.
// - seal is Stamp (a rubber stamp, "approved" as a thing); the StampId badge uses BadgeCheck.
// - family is UsersRound (round heads) against people's Users, the closest pair we can tell
//   apart at 28 px; the label under the glyph carries the rest.
// - police is Siren and the court is Gavel: roles, not people or weapons. "Public safety" is
//   shield.
